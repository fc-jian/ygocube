#!/usr/bin/env python3
"""Emit the first-release year index from a saved YGOPRODeck misc-info export."""

import argparse
from collections import defaultdict
from contextlib import closing
from datetime import date
import json
from pathlib import Path
import sqlite3


def load_aliases(databases):
    rows = {}
    for path in databases:
        with closing(sqlite3.connect(path.resolve(strict=True).as_uri() + '?mode=ro', uri=True)) as db:
            rows.update((code, (alias, kind)) for code, alias, kind in db.execute('SELECT id, alias, type FROM datas'))
    return {code: alias for code, (alias, kind) in rows.items() if not kind & 0x4000}


def release_years(cards, aliases, cutoff):
    parents = {}

    def representative(code):
        while code in parents:
            code = parents[code]
        return code

    for code, alias in aliases.items():
        # Match cardAliasKind in CardsService, including its rules-name exception.
        if code != 5405695 and alias in aliases and 0 < abs(code - alias) < 20:
            left, right = representative(code), representative(alias)
            if left != right:
                parents[max(left, right)] = min(left, right)

    by_identity = {}
    for card in cards:
        years = []
        for info in card.get('misc_info') or []:
            for key in ('ocg_date', 'tcg_date'):
                try:
                    released = date.fromisoformat(info.get(key))
                except (TypeError, ValueError):
                    continue
                if date(1999, 1, 1) <= released <= cutoff:
                    years.append(released.year)
        if not years:
            continue
        code = card['id']
        if code not in aliases:
            matches = {representative(img['id']) for img in card.get('card_images', []) if img['id'] in aliases}
            if len(matches) != 1:
                continue
            code, = matches
        identity = representative(code)
        by_identity[identity] = min(*years, by_identity.get(identity, cutoff.year))

    by_year = defaultdict(list)
    for code in sorted(aliases):
        year = by_identity.get(representative(code))
        if year is not None:
            by_year[year].append(code)
    return by_year


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('metadata', type=Path, help='Saved cardinfo.php?misc=yes response')
    parser.add_argument('cutoff', type=date.fromisoformat)
    parser.add_argument('cdb', type=Path, nargs='+', help='Base CDB followed by expansions in load order')
    args = parser.parse_args()
    cards = json.loads(args.metadata.read_text(encoding='utf-8'))['data']
    years = release_years(cards, load_aliases(args.cdb), args.cutoff)
    print(f'// Generated by scripts/generate-card-release-years.py. Earliest known OCG/TCG release through {args.cutoff}.')
    print('export const FIRST_RELEASE_YEAR_CODES: Readonly<Record<number, readonly number[]>> = {')
    for year, codes in sorted(years.items()):
        print(f'  {year}: [')
        for start in range(0, len(codes), 12):
            print('    ' + ', '.join(map(str, codes[start:start + 12])) + ',')
        print('  ],')
    print('};')


if __name__ == '__main__':
    main()
